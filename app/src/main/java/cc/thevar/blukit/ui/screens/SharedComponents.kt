@Composable
fun MessageContent(message: Message?, themeColor: Color) {
    if (message == null) return
    
    when (message.type) {
        Message.TYPE_TEXT -> {
            Text(
                text = message.content,
                style = MaterialTheme.typography.bodyLarge,
                color = Color.White.copy(alpha = 0.9f)
            )
        }
        Message.TYPE_IMAGE -> {
            Surface(
                modifier = Modifier
                    .fillMaxWidth()
                    .height(200.dp)
                    .clip(RoundedCornerShape(12.dp)),
                color = StealthSurface
            ) {
                Box(contentAlignment = Alignment.Center) {
                    Icon(Icons.Rounded.Image, contentDescription = null, tint = Color.White.copy(alpha = 0.1f), modifier = Modifier.size(48.dp))
                }
            }
        }
        Message.TYPE_FILE -> {
            Surface(
                color = Color.White.copy(alpha = 0.05f),
                shape = RoundedCornerShape(12.dp),
                border = BorderStroke(1.dp, Color.White.copy(alpha = 0.1f))
            ) {
                Row(modifier = Modifier.padding(12.dp), verticalAlignment = Alignment.CenterVertically) {
                    Icon(Icons.Rounded.Description, contentDescription = null, tint = themeColor, modifier = Modifier.size(24.dp))
                    Spacer(modifier = Modifier.width(12.dp))
                    Column {
                        Text(text = message.fileName ?: "Document", style = MaterialTheme.typography.bodySmall, color = Color.White)
                        Text(text = "${(message.fileSize ?: 0) / 1024} KB", style = MaterialTheme.typography.labelSmall, color = Color.White.copy(alpha = 0.4f))
                    }
                }
            }
        }
        Message.TYPE_NOTE_UPDATE, Message.TYPE_ASSIGNMENT_TASK -> {
             cc.thevar.blukit.ui.components.MessageRecordItem(
                record = message,
                onStatusChange = { }, 
                themeColor = themeColor
            )
        }
        Message.TYPE_AI_SUMMARY -> {
            Surface(
                color = StealthAmber.copy(alpha = 0.1f),
                shape = RoundedCornerShape(8.dp),
                border = BorderStroke(1.dp, StealthAmber.copy(alpha = 0.2f))
            ) {
                Row(modifier = Modifier.padding(8.dp), verticalAlignment = Alignment.CenterVertically) {
                    Icon(Icons.Rounded.AutoAwesome, contentDescription = null, tint = StealthAmber, modifier = Modifier.size(14.dp))
                    Spacer(modifier = Modifier.width(8.dp))
                    Text(text = message.content, style = MaterialTheme.typography.bodySmall, color = StealthAmber)
                }
            }
        }
    }
}

