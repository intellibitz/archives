@Composable
fun SourceOptionsMenu(
    device: Source,
    isTied: Boolean,
    isBlocked: Boolean,
    isRequesting: Boolean,
    activeGroupId: String?,
    isAlreadyInActiveGroup: Boolean,
    onMessage: () -> Unit,
    onAccept: () -> Unit,
    onDeny: () -> Unit,
    onDisconnect: () -> Unit,
    onSelect: () -> Unit,
    onIdentify: () -> Unit,
    onBlock: () -> Unit,
    onUnblock: () -> Unit,
    onSync: () -> Unit,
    onAddToGroup: (String) -> Unit,
    onRemoveFromGroup: (String) -> Unit,
    onDismiss: () -> Unit
) {
    AlertDialog(
        onDismissRequest = onDismiss,
        containerColor = StealthSurface,
        title = { 
            Row(verticalAlignment = Alignment.CenterVertically) {
                Text(text = device.emoji, fontSize = 24.sp)
                Spacer(modifier = Modifier.width(12.dp))
                Text(text = (device.name ?: "UNKNOWN").uppercase(), style = MaterialTheme.typography.titleMedium, color = Color.White)
            }
        },
        text = {
            Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                if (isRequesting) {
                    MenuActionItem(Icons.Rounded.Check, "Accept Request", StealthPrimary, onClick = onAccept)
                    MenuActionItem(Icons.Rounded.Close, "Deny Request", StealthError, onClick = onDeny)
                }
                
                MenuActionItem(Icons.Rounded.Message, "Private Whisper", StealthRose, onClick = onMessage)
                MenuActionItem(Icons.Rounded.Fingerprint, "Identify Source", StealthAmber, onClick = onIdentify)
                
                if (activeGroupId != null && activeGroupId != Group.ID_GLOBAL) {
                    if (isAlreadyInActiveGroup) {
                        MenuActionItem(Icons.Rounded.PersonRemove, "Remove from Group", StealthError, onClick = { onRemoveFromGroup(activeGroupId) })
                    } else {
                        MenuActionItem(Icons.Rounded.PersonAdd, "Add to Group", StealthPrimary, onClick = { onAddToGroup(activeGroupId) })
                    }
                }
                
                MenuActionItem(Icons.Rounded.Sync, "Force Sync History", StealthPrimary, onClick = onSync)
                
                if (isBlocked) {
                    MenuActionItem(Icons.Rounded.LockOpen, "Unblock Source", StealthPrimary, onClick = onUnblock)
                } else {
                    MenuActionItem(Icons.Rounded.Block, "Block Source", StealthError, onClick = onBlock)
                }
            }
        },
        confirmButton = {
            TextButton(onClick = onDismiss) { Text("CLOSE", color = Color.White.copy(alpha = 0.4f)) }
        }
    )
}

